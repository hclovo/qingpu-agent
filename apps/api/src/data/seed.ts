function seedOpportunity(
  id: string,
  input: AnalyzeOpportunityInput,
  stage: Opportunity['stage'],
  tags: string[],
  createdDaysAgo: number,
): Opportunity {
  const scoring = scoreOpportunity(input, now)
  const productMatches = matchProducts(input, seedProducts)
  const insight = createRulesInsight(input, scoring, productMatches)
  return {
    id,
    relationshipId: input.relationshipId,
    companyName: input.companyName,
    industry: input.industry,
    region: input.region,
    title: input.title,
    signal: input.signal,
    signalType: input.signalType,
    expectedScale: input.expectedScale,
    maturity: input.maturity,
    contactability: input.contactability,
    stage,
    score: scoring.score,
    grade: scoring.grade,
    scoreVersion: scoring.scoreVersion,
    scoreBreakdown: scoring.dimensions,
    productMatches,
    evidence: [{
      id: `${id}-evidence`,
      kind: input.sourceKind,
      title: input.sourceTitle,
      url: input.sourceUrl,
      occurredAt: input.occurredAt,
      capturedAt: daysAgo(createdDaysAgo),
      excerpt: input.signal,
      confidence: input.sourceKind === 'demo-simulated' ? 0.55 : 0.75,
    }],
    insight: { ...insight, generatedAt: daysAgo(createdDaysAgo) },
    tags: ['演示数据', ...tags],
    isDemo: true,
    createdAt: daysAgo(createdDaysAgo),
    updatedAt: daysAgo(Math.max(0, createdDaysAgo - 1)),
  }
}

