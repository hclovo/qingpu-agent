function touchpoint(
  id: string,
  days: number,
  channel: Touchpoint['channel'],
  summary: string,
  outcome: string,
  nextAction?: string,
  nextDays?: number,
): Touchpoint {
  return {
    id,
    occurredAt: daysAgo(days),
    channel,
    summary,
    outcome,
    nextAction,
    nextActionAt: nextDays === undefined ? undefined : daysFromNow(nextDays),
    createdAt: daysAgo(days),
  }
}

